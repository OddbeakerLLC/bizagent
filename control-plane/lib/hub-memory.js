const fs = require('fs');
const path = require('path');
const { appDir, ensureDir } = require('./config');

const MAX_RECENT_TURNS = 12;
const MAX_SUMMARY_BULLETS = 16;
const MAX_EXCERPT_CHARS = 220;

function hubPromptDir(hub) {
  return path.join(appDir(hub), 'prompts');
}

function hubRuntimePromptFile(hub) {
  return path.join(hubPromptDir(hub), 'hub.md');
}

function hubSessionFile(hub) {
  return path.join(appDir(hub), 'hub-session.md');
}

function extractAgentSections(agentText) {
  const start = agentText.search(/^## § 3\b/m);
  const end = agentText.search(/^## § 5\b/m);
  if (start === -1) throw new Error('AGENT.md is missing § 3');
  return agentText.slice(start, end === -1 ? agentText.length : end).trim();
}

function deriveHubRuntimePrompt(hub) {
  const agentFile = path.join(hub, 'AGENT.md');
  const sections = extractAgentSections(fs.readFileSync(agentFile, 'utf8'));
  const sessionRel = path.relative(hub, hubSessionFile(hub));
  return [
    '# BizAgent Hub Runtime Prompt',
    '',
    'Generated from AGENT.md §§ 3-4. Do not edit this file directly; edit AGENT.md and regenerate prompts.',
    '',
    sections,
    '',
    '## Runtime Memory',
    '',
    `Before responding to the operator, read ${sessionRel}. Treat it as the current chat session memory: a compact rolling summary plus the recent turns needed for continuity.`,
    'Keep that file compact. Compress older turns into the rolling summary, retain only recent turns verbatim, and start a new session when the operator changes topic or explicitly begins a new conversation.',
    'Console-originated inbox messages include a conversation_id frontmatter field. After you finish the operator-visible response or delegation summary, append that hub turn with: node scripts/bizagent-control-plane.js append-hub-turn --conversation <conversation_id> --content-file <path-to-response-markdown>.',
    '',
  ].join('\n');
}

function ensureHubRuntimePrompt(hub) {
  ensureDir(hubPromptDir(hub));
  const file = hubRuntimePromptFile(hub);
  fs.writeFileSync(file, `${deriveHubRuntimePrompt(hub)}\n`);
  if (!fs.existsSync(hubSessionFile(hub))) resetHubSession(hub, { name: 'Main' });
  return file;
}

function excerpt(content) {
  const text = String(content || '').replace(/\s+/g, ' ').trim();
  if (text.length <= MAX_EXCERPT_CHARS) return text;
  return `${text.slice(0, MAX_EXCERPT_CHARS - 3)}...`;
}

function roleLabel(role) {
  return role === 'user' ? 'Operator' : 'Hub';
}

function renderSummary(existingSummary, olderTurns) {
  const lines = [];
  if (existingSummary) lines.push(existingSummary.trim());
  if (olderTurns.length === 0 && lines.length === 0) return '- No older turns summarized yet.';
  const shown = olderTurns.slice(-MAX_SUMMARY_BULLETS);
  const omitted = olderTurns.length - shown.length;
  if (olderTurns.length > 0) lines.push(`- ${olderTurns.length} older turn(s) compressed into summary form.`);
  if (omitted > 0) lines.push(`- ${omitted} earliest summarized turn(s) omitted from this compact runtime file.`);
  for (const turn of shown) {
    lines.push(`- ${roleLabel(turn.role)}: ${excerpt(turn.content)}`);
  }
  return lines.join('\n');
}

function renderRecentTurns(recentTurns) {
  if (recentTurns.length === 0) return '_No recent turns yet._';
  return recentTurns.map((turn) => [
    `### ${roleLabel(turn.role)} - ${turn.created_at || 'unknown time'}`,
    '',
    '```text',
    String(turn.content || '').trim(),
    '```',
  ].join('\n')).join('\n\n');
}

function renderHubSession(conversation) {
  const messages = Array.isArray(conversation.messages) ? conversation.messages : [];
  const recent = messages.slice(-MAX_RECENT_TURNS);
  const older = messages.slice(0, Math.max(0, messages.length - recent.length));
  return [
    '# Hub Session Memory',
    '',
    `Conversation: ${conversation.name || 'Conversation'}`,
    `Started: ${conversation.created_at || 'unknown'}`,
    `Updated: ${conversation.updated_at || new Date().toISOString()}`,
    '',
    '## Rolling Summary',
    '',
    renderSummary(conversation.summary, older),
    '',
    '## Recent Turns',
    '',
    renderRecentTurns(recent),
    '',
  ].join('\n');
}

function resetHubSession(hub, conversation) {
  ensureDir(appDir(hub));
  const file = hubSessionFile(hub);
  const conv = {
    name: (conversation && conversation.name) || 'Conversation',
    created_at: (conversation && conversation.created_at) || new Date().toISOString(),
    updated_at: (conversation && conversation.updated_at) || new Date().toISOString(),
    messages: [],
  };
  fs.writeFileSync(file, renderHubSession(conv));
  return file;
}

function compactHubSession(hub, conversation) {
  ensureDir(appDir(hub));
  const file = hubSessionFile(hub);
  fs.writeFileSync(file, renderHubSession(conversation || {}));
  return file;
}

module.exports = {
  compactHubSession,
  deriveHubRuntimePrompt,
  ensureHubRuntimePrompt,
  extractAgentSections,
  hubRuntimePromptFile,
  hubSessionFile,
  resetHubSession,
};
