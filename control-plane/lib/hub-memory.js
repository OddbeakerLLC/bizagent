function ensureHubRuntimePrompt(hub) {
  ensureDir(hubPromptDir(hub));
  const file = hubRuntimePromptFile(hub);
  fs.writeFileSync(file, `${deriveHubRuntimePrompt(hub)}\n`);
  if (!fs.existsSync(hubSessionFile(hub))) resetHubSession(hub, { name: 'Main' });
  return file;
}

function pathExists(p) {
  try {
    fs.lstatSync(p);
    return true;
  } catch (_err) {
    return false;
  }
}

function ensureSymlink(link, target) {
  if (!pathExists(target)) return false;
  try {
    if (pathExists(link)) {
      const st = fs.lstatSync(link);
      if (st.isSymbolicLink()) {
        const current = fs.readlinkSync(link);
        if (path.resolve(path.dirname(link), current) === path.resolve(target)) return true;
        fs.unlinkSync(link);
      } else {
        return true; // leave non-symlink alone
      }
    }
    fs.symlinkSync(target, link);
    return true;
  } catch (_err) {
    return false;
  }
}

/**
 * Sandbox cwd for hub CLI launches: operational tree without root AGENT.md
 * so workspace project-instruction inject does not re-run §0 "detect built".
 */
function ensureHubRuntimeCwd(hub) {
  const cwd = hubRuntimeCwd(hub);
  ensureDir(cwd);
  const links = [
    'inbox',
    'outbox',
    'journal',
    'agents',
    'user',
    'company',
    'knowledge-stack',
    'logs',
    'scripts',
    'templates',
    'docs',
    'registry.json',
    'cli.json',
    'NIGHTLY.md',
    'WEEKLY.md',
  ];
  for (const name of links) {
    ensureSymlink(path.join(cwd, name), path.join(hub, name));
  }
  // .bizagent → real app dir (session, prompts, locks)
  ensureSymlink(path.join(cwd, '.bizagent'), appDir(hub));
  // Explicitly do NOT link AGENT.md / AGENTS.md — that is the isolation point.
  for (const deny of ['AGENT.md', 'AGENTS.md', 'agent.md', 'agents.md']) {
    const p = path.join(cwd, deny);
    try {
      if (pathExists(p) && fs.lstatSync(p).isSymbolicLink()) fs.unlinkSync(p);
    } catch (_err) {
      /* ignore */
    }
  }
  return cwd;
}

function clip(text, max) {
  const s = String(text || '');
  if (s.length <= max) return s;
  return `${s.slice(0, max - 20)}\n\n…[truncated ${s.length - max + 20} chars]`;
}

function listPendingInboxFiles(hub) {
  const inboxDir = path.join(hub, 'inbox');
  try {
    return fs.readdirSync(inboxDir)
      .filter((f) => f.endsWith('.md') && !f.startsWith('.'))
      .sort()
      .map((f) => path.join(inboxDir, f));
  } catch (_err) {
    return [];
  }
}

function parseConversationId(text) {
  const match = String(text || '').match(/^conversation_id:\s*(.+?)\s*$/m);
  return match ? match[1].trim() : '';
}

/**
 * Build an ephemeral turn prompt: slim system + pending mail + session pointer/excerpt.
 * Written under .bizagent/prompts/turns/; caller deletes after CLI exit.
 */
function buildHubTurnPrompt(hub) {
  ensureHubRuntimePrompt(hub);
  ensureDir(hubTurnsDir(hub));
  const hubAbs = path.resolve(hub);
  const sessionPath = hubSessionFile(hub);
  const sessionRel = path.relative(hub, sessionPath);
  let sessionBody = '';
  try {
    sessionBody = fs.readFileSync(sessionPath, 'utf8');
  } catch (_err) {
    sessionBody = '_No session file yet._';
  }
  const pending = listPendingInboxFiles(hub);
  const conversationIds = [];
  const mailBlocks = pending.map((file) => {
    let body = '';
    try {
      body = fs.readFileSync(file, 'utf8');
    } catch (_err) {
      body = `_unreadable: ${file}_`;
    }
    const cid = parseConversationId(body);
    if (cid) conversationIds.push(cid);
    return [
      `### ${path.basename(file)}`,
      '',
      '```markdown',
      clip(body, MAX_TURN_MAIL_CHARS),
      '```',
      '',
    ].join('\n');
  });

  const convLine = conversationIds.length
    ? conversationIds[conversationIds.length - 1]
    : '(none in pending mail)';

  const turnId = `${Date.now()}-${Math.random().toString(16).slice(2, 8)}`;
  const turnFile = path.join(hubTurnsDir(hub), `hub-${turnId}.md`);

  const content = [
    '# Hub turn prompt (ephemeral)',
    '',
    'Control plane injected this file at launch. Prefer it over rediscovering context with tools.',
    '',
    '## Standing system prompt',
    '',
    deriveHubRuntimePrompt(hub).trim(),
    '',
    '## This turn',
    '',
    `- Hub absolute path: \`${hubAbs}\``,
    `- conversation_id: \`${convLine}\``,
    `- Session file (read-only, already compacted by CP): \`${sessionRel}\``,
    `- Pending inbox files: ${pending.length}`,
    '',
    '### Order',
    '1. Read **Pending mail** and **Session excerpt** below (already inlined — avoid tool-reads unless needed).',
    '2. Write operator reply to `outbox/` → `to: user` with the same `conversation_id` when present.',
    '3. Archive each handled inbox message to `inbox/archive/`.',
    '4. Do not implement product work; do not run setup; do not rewrite session memory.',
    '',
    '## Pending mail',
    '',
    mailBlocks.length ? mailBlocks.join('\n') : '_No pending inbox mail._',
    '',
    '## Session excerpt (CP-compacted; do not rewrite)',
    '',
    '```markdown',
    clip(sessionBody, MAX_TURN_SESSION_CHARS),
    '```',
    '',
  ].join('\n');

  fs.writeFileSync(turnFile, content);
  return turnFile;
}

function listAgentPendingInboxFiles(hub, slug) {
  const inboxDir = path.join(hub, 'agents', slug, 'inbox');
  try {
    return fs.readdirSync(inboxDir)
      .filter((f) => f.endsWith('.md') && !f.startsWith('.'))
      .sort()
      .map((f) => path.join(inboxDir, f));
  } catch (_err) {
    return [];
  }
}

/**
 * Light product-agent turn prompt (Phase 2): standing dispatch text + pending
 * inbox bodies inlined so the agent need not tool-list/read inbox first.
 * Still memoryless across dispatches — injection is per-launch only.
 * Caller deletes the turn file after CLI exit.
 */
function buildAgentTurnPrompt(hub, slug) {
  ensureDir(hubTurnsDir(hub));
  const hubAbs = path.resolve(hub);
  const agentMd = path.join('agents', slug, 'agent.md');
  const dispatchPath = path.join(hub, 'agents', slug, '.dispatch.md');
  let standing = '';
  try {
    standing = fs.readFileSync(dispatchPath, 'utf8').trim();
  } catch (_err) {
    standing = [
      `You are the '${slug}' agent. Read ${agentMd} for your role, scope, and projects.`,
      `Process every message in agents/${slug}/inbox and ignore archive/.`,
      `Write replies to agents/${slug}/outbox; archive each handled message immediately.`,
    ].join('\n');
  }

  const pending = listAgentPendingInboxFiles(hub, slug);
  const subjects = [];
  const mailBlocks = pending.map((file) => {
    let body = '';
    try {
      body = fs.readFileSync(file, 'utf8');
    } catch (_err) {
      body = `_unreadable: ${file}_`;
    }
    const subj = String(body).match(/^subject:\s*(.+?)\s*$/m);
    if (subj) subjects.push(subj[1].trim());
    return [
      `### ${path.basename(file)}`,
      '',
      '```markdown',
      clip(body, MAX_TURN_MAIL_CHARS),
      '```',
      '',
    ].join('\n');
  });

  const turnId = `${Date.now()}-${Math.random().toString(16).slice(2, 8)}`;
  const turnFile = path.join(hubTurnsDir(hub), `agent-${slug}-${turnId}.md`);
  const subjectHint = subjects.length ? subjects.join('; ') : '(none)';

  const content = [
    `# Agent turn prompt (ephemeral) — ${slug}`,
    '',
    'Control plane injected this file at launch. Prefer **Pending mail** below over listing the inbox with tools.',
    'You still run memoryless across dispatches: only this turn is injected.',
    '',
    '## Standing dispatch instructions',
    '',
    standing,
    '',
    '## This turn',
    '',
    `- Hub absolute path: \`${hubAbs}\``,
    `- Agent slug: \`${slug}\``,
    `- Role/scope file: \`${agentMd}\` (open if you need product details not in the mail)`,
    `- Inbox (real files to archive after work): \`agents/${slug}/inbox/\``,
    `- Outbox: \`agents/${slug}/outbox/\``,
    `- Pending subjects: ${subjectHint}`,
    `- Pending inbox files: ${pending.length}`,
    '',
    '### Order',
    '1. Act on **Pending mail** (bodies inlined below). Archive the real files under `agents/' + slug + '/inbox/` after each is done.',
    '2. Write reply messages to `agents/' + slug + '/outbox/` (`to: hub` unless directed otherwise).',
    '3. Before changing project code: read that project\'s `sitemap.md` (Active Work / Known Issues) and recent `.agent/journal/` — skip deep project reads for pure status/ack subjects when mail alone answers.',
    '4. Do not create a worktree unless the dispatch asks or the checkout is unsafe.',
    '',
    '## Pending mail',
    '',
    mailBlocks.length ? mailBlocks.join('\n') : '_No pending inbox mail._',
    '',
  ].join('\n');

  fs.writeFileSync(turnFile, content);
  return turnFile;
}

function excerpt(content) {
  const text = String(content || '').replace(/\s+/g, ' ').trim();
  if (text.length <= MAX_EXCERPT_CHARS) return text;
  return `${text.slice(0, MAX_EXCERPT_CHARS - 3)}...`;
}

function roleLabel(role) {
  return role === 'user' ? 'Operator' : 'Hub';
}

function renderSummary(existingSummary, olderTurns) {
  const lines = [];
  if (existingSummary) lines.push(existingSummary.trim());
  if (olderTurns.length === 0 && lines.length === 0) return '- No older turns summarized yet.';
  const shown = olderTurns.slice(-MAX_SUMMARY_BULLETS);
  const omitted = olderTurns.length - shown.length;
  if (olderTurns.length > 0) lines.push(`- ${olderTurns.length} older turn(s) compressed into summary form.`);
  if (omitted > 0) lines.push(`- ${omitted} earliest summarized turn(s) omitted from this compact runtime file.`);
  for (const turn of shown) {
    lines.push(`- ${roleLabel(turn.role)}: ${excerpt(turn.content)}`);
  }
  return lines.join('\n');
}

function renderRecentTurns(recentTurns) {
  if (recentTurns.length === 0) return '_No recent turns yet._';
  return recentTurns.map((turn) => [
    `### ${roleLabel(turn.role)} - ${turn.created_at || 'unknown time'}`,
    '',
    '```text',
    String(turn.content || '').trim(),
    '```',
  ].join('\n')).join('\n\n');
}

function renderHubSession(conversation) {
  const messages = Array.isArray(conversation.messages) ? conversation.messages : [];
  const recent = messages.slice(-MAX_RECENT_TURNS);
  const older = messages.slice(0, Math.max(0, messages.length - recent.length));
  return [
    '# Hub Session Memory',
    '',
    `Conversation: ${conversation.name || 'Conversation'}`,
    `Started: ${conversation.created_at || 'unknown'}`,
    `Updated: ${conversation.updated_at || new Date().toISOString()}`,
    '',
    '## Rolling Summary',
    '',
    renderSummary(conversation.summary, older),
    '',
    '## Recent Turns',
    '',
    renderRecentTurns(recent),
    '',
  ].join('\n');
}

function resetHubSession(hub, conversation) {
  ensureDir(appDir(hub));
  const file = hubSessionFile(hub);
  const conv = {
    name: (conversation && conversation.name) || 'Conversation',
    created_at: (conversation && conversation.created_at) || new Date().toISOString(),
    updated_at: (conversation && conversation.updated_at) || new Date().toISOString(),
    messages: [],
  };
  fs.writeFileSync(file, renderHubSession(conv));
  return file;
}

function compactHubSession(hub, conversation) {
  ensureDir(appDir(hub));
  const file = hubSessionFile(hub);
  fs.writeFileSync(file, renderHubSession(conversation || {}));
  return file;
}

