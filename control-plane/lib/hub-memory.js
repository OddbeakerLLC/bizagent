const fs = require('fs');
const path = require('path');
const { appDir, ensureDir } = require('./config');

const MAX_RECENT_TURNS = 12;
const MAX_SUMMARY_BULLETS = 16;
const MAX_EXCERPT_CHARS = 220;
/** Cap inline session body in turn prompts (full session still on disk). */
const MAX_TURN_SESSION_CHARS = 6000;
/** Cap each pending mail body embedded in the turn prompt. */
const MAX_TURN_MAIL_CHARS = 8000;

function hubPromptDir(hub) {
  return path.join(appDir(hub), 'prompts');
}

function hubRuntimePromptFile(hub) {
  return path.join(hubPromptDir(hub), 'hub.md');
}

function hubTurnsDir(hub) {
  return path.join(hubPromptDir(hub), 'turns');
}

function hubSessionFile(hub) {
  return path.join(appDir(hub), 'hub-session.md');
}

function hubRuntimeCwd(hub) {
  return path.join(appDir(hub), 'runtime-cwd');
}

function extractAgentSections(agentText) {
  const start = agentText.search(/^## § 3\b/m);
  const end = agentText.search(/^## § 5\b/m);
  if (start === -1) throw new Error('AGENT.md is missing § 3');
  return agentText.slice(start, end === -1 ? agentText.length : end).trim();
}

/**
 * Slim always-on hub runtime prompt (Phase 1).
 * Fat detail (Knowledge Stack, journal schemas, Claude hook, nightly) is
 * on-demand via paths — open only when the turn needs it.
 * Session compaction is owned by the control plane; the LLM must not rewrite
 * hub-session.md.
 */
